def run_hermes(prompt, cwd="/root/workspaces/apexai-os-meta"):
    print(f"\n[HERMES INVOCATION] Executing in {cwd}...")
    res = subprocess.run(["hermes", "-z", prompt], cwd=cwd, capture_output=True, text=True)
    if res.returncode != 0:
        print(f"⚠ Hermes returned exit code {res.returncode}")
        if res.stderr:
            print("Stderr:", res.stderr)
    return res.stdout.strip()

def sha256_file(filepath):
    if not os.path.exists(filepath):
        return None
    h = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(8192):
            h.update(chunk)
    return h.hexdigest()

